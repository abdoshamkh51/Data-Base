-- Q1: Create table
CREATE TABLE EMP_TEST (
    NAME VARCHAR2(100)
);

-- Insert data
INSERT INTO EMP_TEST (NAME) VALUES ('   Ahmed   ');
INSERT INTO EMP_TEST (NAME) VALUES ('   Mohamed   ');
INSERT INTO EMP_TEST (NAME) VALUES ('   Ali   ');

COMMIT;

-- Q2: TRIM
SELECT NAME, TRIM(NAME) AS TRIMMED_NAME
FROM EMP_TEST;

-- Q3: LTRIM
SELECT NAME, LTRIM(NAME) AS LEFT_TRIMMED
FROM EMP_TEST;

-- Q4: RTRIM
SELECT NAME, RTRIM(NAME) AS RIGHT_TRIMMED
FROM EMP_TEST;

-- Q5: TRIM specific character
SELECT TRIM('*' FROM '**Ahmed***') AS RESULT
FROM DUAL;