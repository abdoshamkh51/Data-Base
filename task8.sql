-- Task 7: Aggregate Functions, GROUP BY and HAVING

-- Q1. AVG Function
SELECT AVG(SALARY) AS AVERAGE_SALARY
FROM EMPLOYEES;


-- Q2. COUNT Function
SELECT COUNT(*) AS TOTAL_EMPLOYEES
FROM EMPLOYEES;


-- Q3. MAX Function
SELECT MAX(SALARY) AS MAX_SALARY
FROM EMPLOYEES;


-- Q4. MIN Function
SELECT MIN(SALARY) AS MIN_SALARY
FROM EMPLOYEES;


-- Q5. SUM Function
SELECT SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES;


-- Q6. GROUP BY Department
SELECT
    DEPARTMENT_ID,
    AVG(SALARY) AS AVERAGE_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID;


-- Q7. GROUP BY Job
SELECT
    JOB_ID,
    COUNT(*) AS TOTAL_EMPLOYEES
FROM EMPLOYEES
GROUP BY JOB_ID;


-- Q8. HAVING Clause
SELECT
    DEPARTMENT_ID,
    SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING SUM(SALARY) > 50000;


-- Q9. AVG Commission
SELECT
    AVG(COMMISSION_PCT) AS AVERAGE_COMMISSION
FROM EMPLOYEES
WHERE COMMISSION_PCT IS NOT NULL;


-- Q10. COUNT Employees with Salary > 10000
SELECT
    COUNT(*) AS EMPLOYEES_COUNT
FROM EMPLOYEES
WHERE SALARY > 10000;


-- Q11. MAX and MIN Salary by Job
SELECT
    JOB_ID,
    MAX(SALARY) AS MAX_SALARY,
    MIN(SALARY) AS MIN_SALARY
FROM EMPLOYEES
GROUP BY JOB_ID;


-- Q12. SUM Salary by Manager
SELECT
    MANAGER_ID,
    SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES
GROUP BY MANAGER_ID;


-- Q13. GROUP BY Multiple Columns
SELECT
    DEPARTMENT_ID,
    JOB_ID,
    SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID, JOB_ID;


-- Q14. HAVING with COUNT
SELECT
    JOB_ID,
    COUNT(*) AS TOTAL_EMPLOYEES
FROM EMPLOYEES
GROUP BY JOB_ID
HAVING COUNT(*) > 5;


-- Q15. Aggregate Functions Together
SELECT
    DEPARTMENT_ID,
    COUNT(*) AS TOTAL_EMPLOYEES,
    AVG(SALARY) AS AVERAGE_SALARY,
    MAX(SALARY) AS MAX_SALARY,
    MIN(SALARY) AS MIN_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID;


-- Q16. Complex HAVING
SELECT
    DEPARTMENT_ID,
    AVG(SALARY) AS AVERAGE_SALARY,
    COUNT(*) AS TOTAL_EMPLOYEES
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY) > 8000
AND COUNT(*) < 10;


-- Q17. Department with Highest Total Salary
SELECT
    DEPARTMENT_ID,
    SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY TOTAL_SALARY DESC
FETCH FIRST 1 ROW ONLY;


-- Q18. Using Aliases with Aggregates
SELECT
    DEPARTMENT_ID,
    SUM(SALARY) AS TOTAL_SALARY,
    AVG(SALARY) AS AVERAGE_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID;
